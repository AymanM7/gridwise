GENIE_TITLE = "GridWise - Texas Grid"
GENIE_TABLES = ["gold.strain_hourly", "gold.spike_events", "gold.strain_reference", "gold.forecasts",
                "gold.forecast_drivers", "gold.report_card", "silver.grid_hourly"]
GENIE_INSTRUCTIONS = """GridWise forecasts strain on the ERCOT (Texas) power grid.
* Always answer in Texas local time: use ts_local (America/Chicago). For silver.grid_hourly convert with from_utc_timestamp(ts_utc, 'America/Chicago').
* IMPORTANT: ts_local values are ALREADY Texas wall-clock time even though results display them with a trailing "Z". Never convert ts_local again; report it as-is (e.g. ts_local 2025-07-30T20:00:00Z = 8 PM Texas time on July 30). Only ts_utc / run_ts / target_ts are UTC.
* For history, filter is_forecast_row = false (the last 48 rows are future placeholders with no actuals).
* Net load = demand - wind - solar (MW). Strain index (0-100) = percentile of net load within the same calendar month; level green <60, yellow 60-85, red >85. "Most strained" = highest strain_index, ties broken by net_load_mw.
* A price spike = hourly average real-time price (price_usd_mwh, HB_HUBAVG hub) above $100/MWh (is_spike = 1).
* Summer = June-August; winter = December-February. "Last <month>" = the most recent completed occurrence of that month.
* gold.forecasts holds one 48-hour batch per run_ts; the current forecast is WHERE run_ts = (SELECT max(run_ts) FROM gold.forecasts). spike_prob is 0-1.
* report_card mape / demand_mape / band_coverage are fractions (0.032 = 3.2%).
* Round MW to whole numbers and prices to whole dollars."""
GENIE_QA = [
    ("What was the most strained hour of summer 2025?",
     "SELECT ts_local, round(net_load_mw, 0) AS net_load_mw, round(strain_index, 1) AS strain_index, level\n"
     "FROM {c}.gold.strain_hourly\n"
     "WHERE NOT is_forecast_row AND ts_local >= '2025-06-01' AND ts_local < '2025-09-01'\n"
     "ORDER BY strain_index DESC, net_load_mw DESC LIMIT 1"),
    ("How does wind output change on peak-demand days?",
     "WITH d AS (\n"
     "  SELECT to_date(from_utc_timestamp(ts_utc, 'America/Chicago')) AS day, max(demand_mw) AS peak_demand_mw,\n"
     "         avg(wind_mw) AS avg_wind_mw\n"
     "  FROM {c}.silver.grid_hourly\n"
     "  WHERE NOT is_forecast_row AND demand_mw IS NOT NULL AND wind_mw IS NOT NULL GROUP BY 1),\n"
     "r AS (SELECT *, percent_rank() OVER (ORDER BY peak_demand_mw) AS pr FROM d)\n"
     "SELECT CASE WHEN pr >= 0.9 THEN 'peak-demand days (top 10%)' ELSE 'all other days' END AS day_type,\n"
     "       count(*) AS days, round(avg(peak_demand_mw), 0) AS avg_peak_demand_mw, round(avg(avg_wind_mw), 0) AS avg_wind_mw\n"
     "FROM r GROUP BY 1 ORDER BY 1"),
    ("How many hours had real-time prices above $100/MWh last August?",
     "SELECT count(*) AS hours_above_100, round(max(price_usd_mwh), 0) AS max_hourly_price\n"
     "FROM {c}.gold.spike_events\n"
     "WHERE price_usd_mwh > 100\n"
     "  AND ts_local >= make_date(year(current_date()) - CASE WHEN month(current_date()) > 8 THEN 0 ELSE 1 END, 8, 1)\n"
     "  AND ts_local <  make_date(year(current_date()) - CASE WHEN month(current_date()) > 8 THEN 0 ELSE 1 END, 9, 1)"),
    ("What's the average net load at 6pm in July vs. January?",
     "SELECT CASE month(ts_local) WHEN 1 THEN 'January' ELSE 'July' END AS month_name, count(*) AS hours,\n"
     "       round(avg(net_load_mw), 0) AS avg_net_load_mw_6pm\n"
     "FROM {c}.gold.strain_hourly\n"
     "WHERE NOT is_forecast_row AND hour(ts_local) = 18 AND month(ts_local) IN (1, 7)\n"
     "GROUP BY 1 ORDER BY 1"),
    ("Which weekday has the highest average strain index?",
     "SELECT date_format(ts_local, 'EEEE') AS weekday, round(avg(strain_index), 1) AS avg_strain_index, count(*) AS hours\n"
     "FROM {c}.gold.strain_hourly WHERE NOT is_forecast_row\n"
     "GROUP BY 1 ORDER BY avg_strain_index DESC"),
]


def _lines(text: str) -> list[str]:
    return text.splitlines(keepends=True)


def genie_serialized(catalog: str) -> str:
    import uuid
    ids = lambda n: sorted(uuid.uuid4().hex for _ in range(n))  # noqa: E731 (sorted: API wants ordered ids)
    q_ids, sql_ids, b_ids = ids(len(GENIE_QA)), ids(len(GENIE_QA)), ids(len(GENIE_QA))
    space = {
        "version": "2",
        "config": {"sample_questions": [{"id": i, "question": [q]} for i, (q, _) in zip(q_ids, GENIE_QA)]},
        "data_sources": {"tables": [{"identifier": f"{catalog}.{t}"} for t in sorted(GENIE_TABLES)]},
        "instructions": {
            "text_instructions": [{"id": uuid.uuid4().hex, "content": _lines(GENIE_INSTRUCTIONS)}],
            "example_question_sqls": [{"id": i, "question": [q], "sql": _lines(s.format(c=catalog))}
                                      for i, (q, s) in zip(sql_ids, GENIE_QA)],
        },
        "benchmarks": {"questions": [
            {"id": i, "question": [q], "answer": [{"format": "SQL", "content": _lines(s.format(c=catalog))}]}
            for i, (q, s) in zip(b_ids, GENIE_QA)]},
    }
    return json.dumps(space)


def genie() -> str:
    import os
    s = get_settings()
    w = _client()
    wid = os.getenv("DATABRICKS_WAREHOUSE_ID") or next(iter(w.warehouses.list())).id
    desc = ("Ask questions about ERCOT grid history (net load, strain index, price spikes, wind/solar) and "
            "GridWise's 48h forecasts and accuracy report card.")
    existing = None
    for sp in (w.genie.list_spaces().spaces or []):
        if sp.title == GENIE_TITLE:
            existing = sp.space_id
    ser = genie_serialized(s.catalog)
    if existing:
        w.genie.update_space(existing, serialized_space=ser, title=GENIE_TITLE, description=desc, warehouse_id=wid)
        sid = existing
        print(f"Updated Genie space {sid}")
    else:
        sid = w.genie.create_space(warehouse_id=wid, serialized_space=ser, title=GENIE_TITLE,
                                   description=desc).space_id
        print(f"Created Genie space {sid}")
    from tools.login import set_env
    set_env("GENIE_SPACE_ID", sid)
    print(f"  {s.databricks_host}/genie/rooms/{sid}  (saved GENIE_SPACE_ID to .env)")
    return sid


def _client() -> WorkspaceClient:
    s = get_settings()
    if not s.has_databricks:
        sys.exit("DATABRICKS_HOST / DATABRICKS_TOKEN missing in .env")
    return WorkspaceClient(host=s.databricks_host, token=s.databricks_token)


def missing_notebooks() -> list[str]:
    return [f"{f}/{nb}.py" for _, f, nb, _ in TASKS if not (ROOT / f / f"{nb}.py").exists()]


def job_settings(w: WorkspaceClient, catalog: str) -> dict:
    root = remote_root(w)
    tasks = [
        jobs.Task(
            task_key=key,
            description=f"{folder}/{nb}",
            notebook_task=jobs.NotebookTask(notebook_path=f"{root}/{folder}/{nb}",
                                            source=jobs.Source.WORKSPACE),
            depends_on=[jobs.TaskDependency(task_key=d) for d in deps],
            # all_success: a failed upstream stops the chain, so stale gold never feeds predict
            # (genie_comments runs regardless: comments are harmless metadata and must survive 03_gold)
            run_if=jobs.RunIf.ALL_DONE if key == COMMENTS_TASK[0] else jobs.RunIf.ALL_SUCCESS,
            timeout_seconds=1800,
            environment_key=ENV_KEY,
        )
        # no cluster spec + environment_key -> serverless compute pinned to ENV_VERSION (Free Edition)
        for key, folder, nb, deps in TASKS + [COMMENTS_TASK]
    ]
    return dict(
        name=JOB_NAME,
        tasks=tasks,
        parameters=[jobs.JobParameterDefinition(name="catalog", default=catalog)],
        environments=[jobs.JobEnvironment(environment_key=ENV_KEY,
                                          spec=compute.Environment(environment_version=ENV_VERSION))],
        max_concurrent_runs=1,
        timeout_seconds=3600,
        tags={"project": "gridwise", "phase": "4.5"},
        queue=jobs.QueueSettings(enabled=True),
    )


def find_job(w: WorkspaceClient) -> int | None:
    for j in w.jobs.list(name=JOB_NAME):
        if j.settings and j.settings.name == JOB_NAME:
            return j.job_id
    return None


def create(wait_minutes: int = 40) -> int:
    deadline = time.time() + wait_minutes * 60
    while (miss := missing_notebooks()):
        if time.time() > deadline:
            sys.exit(f"still missing after {wait_minutes} min: {', '.join(miss)}")
        print(f"  waiting for {', '.join(miss)} ... (re-checking in 60s)")
        time.sleep(60)

    s = get_settings()
    w = _client()
    print("Uploading notebooks ...")
    upload(w)
    upload_comments_notebook(w)
    cfg = job_settings(w, s.catalog)
    job_id = find_job(w)
    if job_id:
        w.jobs.reset(job_id=job_id, new_settings=jobs.JobSettings(**cfg))
        print(f"Updated job '{JOB_NAME}' (id {job_id})")
    else:
        job_id = w.jobs.create(**cfg).job_id
        print(f"Created job '{JOB_NAME}' (id {job_id})")
    from tools.login import set_env
    set_env("DATABRICKS_JOB_ID", str(job_id))
    print("Saved DATABRICKS_JOB_ID to .env")
    print(f"  {s.databricks_host}/jobs/{job_id}")
    return job_id


def _job_id(w: WorkspaceClient) -> int:
    s = get_settings()
    if s.job_id:
        return int(s.job_id)
    jid = find_job(w)
    if not jid:
        sys.exit("job not found; run: python -m tools.job create")
    return jid


def report(w: WorkspaceClient, run_id: int) -> bool:
    """Print one line per task (state, duration, notebook exit summary). Returns overall success."""
    run = w.jobs.get_run(run_id)
    order = {k: i for i, (k, *_rest) in enumerate(TASKS + [COMMENTS_TASK])}
    print(f"Run {run.run_id}: {run.state.life_cycle_state} / {run.state.result_state}  {run.run_page_url}")
    ok = run.state.result_state == jobs.RunResultState.SUCCESS
    # run.tasks holds every attempt (serverless auto-retries + repairs): show the latest one per task
    latest, attempts = {}, {}
    for t in run.tasks or []:
        attempts[t.task_key] = attempts.get(t.task_key, 0) + 1
        if t.task_key not in latest or (t.start_time or 0) >= (latest[t.task_key].start_time or 0):
            latest[t.task_key] = t
    for t in sorted(latest.values(), key=lambda t: order.get(t.task_key, 99)):
        st = t.state
        res = st.result_state.value if st and st.result_state else (st.life_cycle_state.value if st else "?")
        secs = round((t.execution_duration or 0) / 1000) if t.execution_duration else \
            round(((t.end_time or 0) - (t.start_time or 0)) / 1000) if t.end_time else 0
        summary = ""
        try:
            out = w.jobs.get_run_output(t.run_id)
            if out.error:
                summary = f"error: {out.error[:300]}"
            elif out.notebook_output and out.notebook_output.result:
                raw = out.notebook_output.result
                try:
                    d = json.loads(raw)
                    keep = {k: d[k] for k in ("all_pass", "failed", "run_ts", "rows", "n_rows") if k in d}
                    summary = json.dumps(keep or d)[:300]
                except ValueError:
                    summary = raw[:300]
        except Exception as ex:  # output not available for skipped tasks
            summary = f"({type(ex).__name__})" if res not in ("UPSTREAM_FAILED", "SKIPPED") else ""
        tries = f"x{attempts[t.task_key]}" if attempts[t.task_key] > 1 else ""
        print(f"  {t.task_key:<14} {res:<16} {secs:>5}s {tries:<3} {summary}")
    return ok


def run() -> bool:
    w = _client()
    jid = _job_id(w)
    print(f"Running job {jid} ...")
    waiter = w.jobs.run_now(job_id=jid)
    try:
        r = waiter.result(timeout=__import__("datetime").timedelta(minutes=60))
        rid = r.run_id
    except Exception as ex:  # failed runs raise OperationFailed; still report tasks
        print(f"  ({type(ex).__name__}: {str(ex)[:200]})")
        rid = waiter.response.run_id
    return report(w, rid)


def last() -> bool:
    w = _client()
    runs = list(w.jobs.list_runs(job_id=_job_id(w), limit=1, expand_tasks=False))
    if not runs:
        sys.exit("no runs yet")
    return report(w, runs[0].run_id)


def show() -> None:
    w = _client()
    j = w.jobs.get(_job_id(w))
    print(f"{j.settings.name} (id {j.job_id}) max_concurrent_runs={j.settings.max_concurrent_runs} "
          f"schedule={'none' if not j.settings.schedule else j.settings.schedule.quartz_cron_expression}")
    for t in j.settings.tasks:
        deps = ",".join(d.task_key for d in (t.depends_on or [])) or "-"
        print(f"  {t.task_key:<14} <- {deps:<22} {t.notebook_task.notebook_path}")


def main():
    p = argparse.ArgumentParser(prog="tools.job")
    p.add_argument("cmd", choices=["create", "run", "last", "show", "comments", "genie"])
    p.add_argument("--wait-minutes", type=int, default=40, help="create: how long to wait for missing notebooks")
    a = p.parse_args()
    if a.cmd == "create":
        create(a.wait_minutes)
    elif a.cmd == "genie":
        genie()
    elif a.cmd == "comments":
        apply_comments()
    elif a.cmd == "show":
        show()
    else:
        ok = run() if a.cmd == "run" else last()
        sys.exit(0 if ok else 1)


if __name__ == "__main__":
    main()
