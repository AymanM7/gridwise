def _q(s: str) -> str:
    return s.replace("\\", "\\\\").replace("'", "\\'")


def comment_statements(catalog: str) -> list[str]:
    out = [f"COMMENT ON TABLE {catalog}.{t} IS '{_q(c)}'" for t, c in TABLE_COMMENTS.items()]
    for t, cols in COLUMN_COMMENTS.items():
        out += [f"ALTER TABLE {catalog}.{t} ALTER COLUMN {col} COMMENT '{_q(c)}'" for col, c in cols.items()]
    return out


def apply_comments() -> None:
    """Apply table + column comments now through the SQL warehouse (no notebook compute)."""
    from tools.sql import query
    ok, bad = 0, 0
    for st in comment_statements(get_settings().catalog):
        try:
            query(st)
            ok += 1
        except Exception as ex:
            bad += 1
            print(f"  failed: {st[:80]} ... {str(ex)[:150]}")
    print(f"comments applied: {ok} ok, {bad} failed")


